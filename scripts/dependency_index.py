"""The dependency manifest's generated parts: the pinned archives and every hash each patch script
accepts or writes, read from CMakeLists.txt and cmake/Patch*.cmake.

    python scripts/dependency_index.py           print the generated section
    python scripts/dependency_index.py --write   replace it in docs/dependencies.md
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
START, END = "<!-- dependency-index:start -->", "<!-- dependency-index:end -->"


def archives():
    """(name, revision, archive SHA-256) for each pinned download in CMakeLists.txt."""
    text = (ROOT / "CMakeLists.txt").read_text()
    found = []
    for name, url, digest in re.findall(r"FetchContent_Declare\(\s*(\w+)\s+URL (\S+)\s+URL_HASH SHA256=([0-9a-f]{64})", text):
        found.append((name, url.rsplit("/", 1)[-1], digest))
    return found


def patch_hashes(script):
    """(role, SHA-256) for each hash a patch script names, in order, without repeats."""
    seen, rows = set(), []
    for line in script.read_text().splitlines():
        for digest in re.findall(r"\b[0-9a-f]{64}\b", line):
            if digest in seen:
                continue
            seen.add(digest)
            named = re.search(r"set\((\w+)\s", line)
            rows.append((named.group(1) if named else "accepted input", digest))
    return rows


def section():
    lines = [START, "", "Generated by `scripts/dependency_index.py` from the build; `tests/test_dependencies.py` checks it is current.", "",
             "| Pinned archive | Revision | Archive SHA-256 |", "| --- | --- | --- |"]
    lines += [f"| {name} | `{revision}` | `{digest}` |" for name, revision, digest in archives()]
    lines += ["", "| Patch script | Hash | SHA-256 |", "| --- | --- | --- |"]
    for script in sorted((ROOT / "cmake").glob("Patch*.cmake")):
        lines += [f"| `cmake/{script.name}` | {role} | `{digest}` |" for role, digest in patch_hashes(script)]
    lines += ["", END]
    return "\n".join(lines)


def write():
    doc = ROOT / "docs" / "dependencies.md"
    text = doc.read_text()
    if START in text:
        before, rest = text.split(START, 1)
        text = before + section() + rest.split(END, 1)[1]
    else:
        text = text.rstrip("\n") + "\n\n## Patch and archive hash index\n\n" + section() + "\n"
    doc.write_text(text)


if __name__ == "__main__":
    if "--write" in sys.argv:
        write()
    else:
        print(section())
